/**
 * 初始化八字科普词条数据
 * POST /api/glossary/bazi/init
 */
export async function POST() {
  try {
    const client = getPgClient();
    
    // 插入数据（如果不存在）
    for (const item of BAZI_GLOSSARY_DATA) {
      await client
        .from('glossary')
        .upsert({
          term: item.term,
          category: item.category,
          short_desc: item.short_desc,
          full_desc: item.full_desc,
          origin: item.origin,
          examples: item.examples,
          related_terms: item.related_terms,
        }, {
          onConflict: 'term',
          ignoreDuplicates: false,
        });
    }
    
    return NextResponse.json({ 
      message: '八字词条初始化成功',
      count: BAZI_GLOSSARY_DATA.length 
    });
  } catch (error) {
    console.error('初始化八字词条失败:', error);
    return NextResponse.json({ 
      error: '初始化失败',
      details: error instanceof Error ? error.message : 'Unknown error'
    }, { status: 500 });
  }
}
