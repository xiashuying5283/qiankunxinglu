// 导出根据上下卦查找卦象的函数
export function findHexagram(upper: string, lower: string): HexagramData | undefined {
  return hexagrams.find(h => h.upperTrigram === upper && h.lowerTrigram === lower);
}

// 导出根据卦名查找卦象的函数
export function findHexagramByName(name: string): HexagramData | undefined {
  return hexagrams.find(h => h.name === name);
}

// 导出根据卦序查找卦象的函数
export function findHexagramByNumber(num: number): HexagramData | undefined {
  return hexagrams.find(h => h.number === num);
}
